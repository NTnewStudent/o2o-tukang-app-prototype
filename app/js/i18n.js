function t(path) {
  const lang = (typeof AppState !== "undefined" && AppState.lang()) || "en";
  const parts = path.split(".");
  let cur = I18N[lang];
  for (const p of parts) {
    if (cur && Object.prototype.hasOwnProperty.call(cur, p)) cur = cur[p];
    else {
      cur = I18N.en;
      for (const q of parts) cur = cur && cur[q];
      break;
    }
  }
  return typeof cur === "string" ? cur : path;
}

function locName(obj) {
  const lang = AppState.lang();
  if (!obj) return "";
  if (obj.nameEn) return lang === "id" ? obj.nameId : obj.nameEn;
  if (obj.en && obj.idn) return lang === "id" ? obj.idn : obj.en;
  return obj.name || obj.id;
}
